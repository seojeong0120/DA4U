def preprocess_csv_files():
    """dataframe.ipynb의 전처리 코드를 기반으로 원본 CSV 파일들을 직접 수정"""
    
    print("=== 데이터 로드 및 전처리 시작 ===")
    
    # 1. 원본 데이터 로드
    df1 = pd.read_csv("../dataset/big_data_set1_f.csv", encoding="cp949")
    df2 = pd.read_csv("../dataset/big_data_set2_f.csv", encoding="cp949")
    df3 = pd.read_csv("../dataset/big_data_set3_f.csv", encoding="cp949")
    
    print(f"원본 데이터 크기 - df1: {df1.shape}, df2: {df2.shape}, df3: {df3.shape}")
    
    # 2. 컬럼명 변경
    df1.columns = ["코드", "기준면적", "가맹점명", "브랜드코드", "지역", "업종", "상권", "개설일", "폐업일"]
    df2.columns = ["코드", "기준년월", "운영개월수", "매출금액", "매출건수", "유니크고객수", "객단가", 
                   "취소율", "배달매출비율", "동종매출금액%", "동종매출건수%", "동종매출순위%", 
                   "동일상권매출순위%", "동종해지가맹점%", "동일상권해지가맹점비중"]
    df3.columns = ["코드", "기준년월", "남20대이하", "남30대", "남40대", "남50대", "남60대이상",
                   "여20대이하", "여30대", "여40대", "여50대", "여60대이상", "재방문고객", 
                   "신규고객", "거주이용고객", "직장이용고객", "유동인구이용고객"]
    
    # 3. df2와 df3를 병합
    print("=== df2와 df3 병합 ===")
    df23 = pd.merge(df2, df3, on=["코드", "기준년월"], how="outer", suffixes=("_x", "_y"))
    print(f"df23 병합 완료: {df23.shape}")
    
    # 4. 키 타입 맞추기 및 df1과 병합
    print("=== df1과 df23 병합 ===")
    df23['코드'] = df23['코드'].astype(str)
    df1['코드'] = df1['코드'].astype(str)
    
    # df1에서 중복 제거 (폐업일, 개설일 기준으로 정렬 후 마지막 것만 유지)
    df1_u = df1.sort_values(['코드','폐업일','개설일']).drop_duplicates('코드', keep='last')
    
    # 병합
    df = df1_u.merge(df23, on="코드", how="right", validate="1:m")
    print(f"최종 병합 완료: {df.shape}")
    
    # 5. 상권 데이터 로드 및 병합
    print("=== 상권 데이터 병합 ===")
    try:
        상권_df = pd.read_csv("../dataset/상권.csv", encoding="utf-8-sig", sep=None, engine="python")
        
        # 필요한 열들만 선택
        상권_매핑 = 상권_df[['ENCODED_MCT', 'TRDAR_CD_N', 'SIGNGU_CD_', 'ADSTRD_CD_']].copy()
        상권_매핑['ENCODED_MCT'] = 상권_매핑['ENCODED_MCT'].astype(str)
        
        # 병합
        df_merged = df.merge(상권_매핑, left_on='코드', right_on='ENCODED_MCT', how='left')
        df_merged = df_merged.drop('ENCODED_MCT', axis=1)
        
        # 컬럼명 변경
        df_merged = df_merged.rename(columns={
            'TRDAR_CD_N': '상권코드',
            'SIGNGU_CD_': '시군구코드', 
            'ADSTRD_CD_': '행정동코드'
        })
        
        df = df_merged.copy()
        print(f"상권 데이터 병합 완료: {df.shape}")
        
        # 상권코드 결측치 처리
        df['상권'] = df['상권'].fillna('미표기')
        df['상권코드'] = df['상권코드'].fillna(df['상권'])
        
    except FileNotFoundError:
        print("상권.csv 파일을 찾을 수 없습니다. 상권 데이터 병합을 건너뜁니다.")
        df['상권'] = df['상권'].fillna('미표기')
    
    # 6. 백분율 구간 치환
    print("=== 백분율 구간 치환 ===")
    mapping = {
        '1_10%이하': '10%', 
        '2_10-25%': '25%',
        '3_25-50%': '50%',
        '4_50-75%': '75%',
        '5_75-90%': '90%',   
        '6_90%초과(하위 10% 이하)': '100%'
    }
    
    cols = ['운영개월수', '매출금액', '매출건수', '유니크고객수', '객단가']
    for c in cols:
        df[c] = df[c].map(mapping).fillna(df[c])
    
    # 7. 취소율 구간 치환
    mapping2 = {
        '1_상위1구간': '상위1',
        '2_상위2구간': '상위2',
        '3_상위3구간': '상위3',
        '4_상위4구간': '상위4',
        '5_상위5구간': '상위5',
        '6_상위6구간(하위1구간)': '상위6'
    }
    df['취소율'] = df['취소율'].replace(mapping2)
    
    # 8. 특수값 처리
    df = df.replace(-999999.9, np.nan)
    
    # 9. 업종 분류 컬럼 추가
